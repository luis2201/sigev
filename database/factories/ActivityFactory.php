     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'description' => fake()->sentence(), 'registered_at' => now('UTC'), 'created_by' => User::factory(), 'status' => 'draft',
        ];
    }
}
